    window.modHubGetMarketCardText = function (entry, field, locale = window.modHubGetLanguage?.() || 'zh-CN') {
        const source = typeof entry?.[field] === 'string' ? entry[field] : '';
        const dictionaries = field === 'name' ? ['localizedNames', 'nameI18n', 'names']
            : ['localizedDescriptions', 'descriptionI18n', 'descriptions'];
        let translated;
        for (const key of dictionaries) {
            const value = entry?.[key]?.[locale];
            if (typeof value === 'string' && value.trim()) { translated = value; break; }
        }
        const variant = field === 'name' && window.modHubMarketVariants?.normalizeVariant(entry?.variant);
        const suffix = variant && source.endsWith(`（${variant.label}）`) ? `（${variant.label}）` : '';
        const base = suffix ? source.slice(0, -suffix.length) : source;
        const bundled = cardTranslations.get(base);
        if (!translated && locale !== 'zh-CN' && bundled) {
            translated = bundled[locale === 'zh-TW' ? 0 : 1];
            if (suffix) translated += `（${cardTranslations.get(variant.label)?.[locale === 'zh-TW' ? 0 : 1] || variant.label}）`;
        }
        return { source, text: translated || source, translated: Boolean(translated && translated !== source),
            missing: locale !== 'zh-CN' && /[\u3400-\u9fff]/u.test(base) && !translated };
    };
